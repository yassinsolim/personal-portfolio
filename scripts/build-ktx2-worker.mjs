// writes static/basis/ktx2-worker.js and basis_transcoder.wasm: the KTX2
// decoder as a real same origin worker file. three's KTX2Loader builds the
// same script into a blob worker, which would run under the page's policy,
// and the emscripten transcoder needs 'unsafe-eval'. as its own file it gets
// its own, narrower policy from vercel.json and the page stays strict.
// runs as part of prebuild; the output is generated, not committed
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { KTX2Loader } from 'three/examples/jsm/loaders/KTX2Loader.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const basis = path.join(root, 'node_modules/three/examples/jsm/libs/basis');
const out = path.join(root, 'static/basis');

const transcoder = await fs.readFile(path.join(basis, 'basis_transcoder.js'), 'utf8');
const fn = KTX2Loader.BasisWorker.toString();
const body = [
    '/* generated by scripts/build-ktx2-worker.mjs from three.js KTX2Loader, do not edit */',
    'let _EngineFormat = ' + JSON.stringify(KTX2Loader.EngineFormat),
    'let _EngineType = ' + JSON.stringify(KTX2Loader.EngineType),
    'let _TranscoderFormat = ' + JSON.stringify(KTX2Loader.TranscoderFormat),
    'let _BasisFormat = ' + JSON.stringify(KTX2Loader.BasisFormat),
    '/* basis_transcoder.js */',
    transcoder,
    '/* worker */',
    fn.substring(fn.indexOf('{') + 1, fn.lastIndexOf('}')),
].join('\n');

await fs.mkdir(out, { recursive: true });
await fs.writeFile(path.join(out, 'ktx2-worker.js'), body);
await fs.copyFile(path.join(basis, 'basis_transcoder.wasm'), path.join(out, 'basis_transcoder.wasm'));
// for the fallback test (?raceDebug=1&ktx2fail=hang): a worker that never answers
await fs.writeFile(path.join(out, 'hang-worker.js'), '/* generated, test only: never answers */\nself.onmessage = () => {};\n');
console.log(`[ktx2-worker] wrote static/basis/ktx2-worker.js (${(body.length / 1024).toFixed(0)} KB)`);
